#!/usr/bin/env node
// Builds lib/perfume-render/index.cjs from parfumdeclaration's renderer (lib/perfume-render/entry.ts) and
// copies its fonts, shop logos and the Real-ESRGAN model next to it. sharp and onnxruntime-node stay external.
//   node scripts/build-perfume-render.cjs [path-to-parfumdeclaration-web]
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const root = path.resolve(__dirname, "..");
const pd = path.resolve(process.argv[2] || path.join(root, "..", "parfumdeclaration-web"));
const outDir = path.join(root, "lib", "perfume-render");
const esbuild = path.join(pd, "node_modules", ".bin", process.platform === "win32" ? "esbuild.cmd" : "esbuild");

execFileSync(esbuild, [
  path.join(outDir, "entry.ts"),
  "--bundle", "--platform=node", "--format=cjs", "--target=node20",
  "--external:sharp", "--external:onnxruntime-node",
  `--outfile=${path.join(outDir, "index.cjs")}`,
], { stdio: "inherit", shell: process.platform === "win32" });

// The sources find their files relative to apps/api/{dist,src}/lib — point them at this folder instead
const bundle = path.join(outDir, "index.cjs");
let code = fs.readFileSync(bundle, "utf8");
const before = code;
code = code.replace(/(["'])\.\.\/\.\.\/assets\/perfume-card\1/g, '"./assets"').replace(/(["'])\.\.\/\.\.\/models\//g, '$1./models/');
if (code === before) throw new Error("asset / model paths not found in the bundle — check the sources");
fs.writeFileSync(bundle, `// GENERATED by scripts/build-perfume-render.cjs from parfumdeclaration-web — do not edit\n${code}`);

const copy = (from, to) => {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.cpSync(from, to, { recursive: true });
};
copy(path.join(pd, "apps", "api", "assets", "perfume-card"), path.join(outDir, "assets"));
copy(path.join(pd, "apps", "api", "models"), path.join(outDir, "models"));
console.log("built", path.relative(root, bundle), `${Math.round(fs.statSync(bundle).size / 1024)} KB`);
